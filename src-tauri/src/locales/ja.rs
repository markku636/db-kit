//! - 未収録の key は `i18n::lookup` が**英語**（次選言語）へフォールバックする。中国語が
//!   そのまま出ることはないので、部分的な収録でも運用できる。
//! - 収録するのは利用者が実際に目にする文言（エラー・CLI 出力）から。新しい文言を足すときは
//!   対応する行を 1 行追加すればよい（並び順のメンテナンスは不要）。
